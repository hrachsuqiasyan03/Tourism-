class TouristPlace {
  final String name;
  final String region;
  final String city;
  final String description;
  final String image;
  final double latitude;
  final double longitude;

  const TouristPlace({
    required this.name,
    required this.region,
    required this.city,
    required this.description,
    required this.image,
    required this.latitude,
    required this.longitude,
  });
}